import { Component, memo, useMemo, useState } from 'react'
import type { ReactNode } from 'react'
import { Link } from 'react-router-dom'
import Markdown from 'react-markdown'
import type { Components, Options } from 'react-markdown'
import remarkGfm from 'remark-gfm'
import remarkMath from 'remark-math'
import rehypeSanitize, { defaultSchema } from 'rehype-sanitize'
import rehypeKatex from 'rehype-katex'
import remend from 'remend'
import type { Element, Root, RootContent } from 'hast'
import type { VFile } from 'vfile'
import 'katex/dist/katex.min.css'

export type MarkdownMode = 'complete' | 'streaming' | 'partial'
export interface MessageMarkdownProps { text: string; mode?: MarkdownMode; messageKey: string }

const remarkPlugins: NonNullable<Options['remarkPlugins']> = [remarkGfm, [remarkMath, { singleDollarTextMath: false }]]
const schema: Parameters<typeof rehypeSanitize>[0] = {
  ...defaultSchema,
  // All identifiers are generated by the parser and namespaced below; raw HTML becomes text.
  clobberPrefix: '',
  attributes: { ...defaultSchema.attributes, code: [['className', /^language-./, 'math-inline', 'math-display']] },
}
const incompleteOptions = {
  bold: true, boldItalic: true, italic: true, inlineCode: true, strikethrough: true,
  links: true, images: false, linkMode: 'text-only' as const,
  htmlTags: false, comparisonOperators: false, singleTilde: false, setextHeadings: false,
  katex: true, inlineKatex: false,
}

function walk(node: Root | RootContent, visit: (node: RootContent) => void) {
  if (node.type !== 'root') visit(node)
  if ('children' in node) node.children.forEach(child => walk(child, visit))
}

/** Preserve HTML literally, suppress image requests, and isolate generated footnotes per answer. */
function presentationTree({ prefix }: { prefix: string }) {
  return (tree: Root) => {
    walk(tree, node => {
      if (node.type === 'raw') Object.assign(node, { type: 'text', value: node.value })
      if (node.type === 'element' && node.tagName === 'img') {
        Object.assign(node, { type: 'text', value: String(node.properties.alt ?? '') })
      }
    })
    const ids = new Set<string>()
    walk(tree, node => { if (node.type === 'element' && node.properties.id) ids.add(String(node.properties.id)) })
    walk(tree, node => {
      if (node.type !== 'element') return
      if (node.properties.id) node.properties.id = prefix + node.properties.id
      const href = node.properties.href
      if (typeof href === 'string' && href.startsWith('#') && ids.has(href.slice(1))) node.properties.href = '#' + prefix + href.slice(1)
      if (Array.isArray(node.properties.ariaDescribedBy)) node.properties.ariaDescribedBy = node.properties.ariaDescribedBy.map(id => prefix + id)
    })
  }
}

/** Render each equation independently and replace unsupported expressions with their source. */
function scientificMath() {
  return (tree: Root, file: VFile) => {
    const process = (parent: Root | Element) => {
      for (let i = 0; i < parent.children.length; i++) {
        const node = parent.children[i]
        if (node.type !== 'element') continue
        const code = node.tagName === 'pre' ? node.children.find(child => child.type === 'element' && child.tagName === 'code') as Element | undefined : node
        const classes = code?.properties.className
        const equation = code?.tagName === 'code' && Array.isArray(classes) && classes.some(value => ['language-math', 'math-inline', 'math-display'].includes(String(value)))
        if (!equation) { process(node); continue }
        const value = textOf(node)
        const local: Root = { type: 'root', children: [node] }
        const before = file.messages.length
        const blocked = /\\(?:href|url|includegraphics|htmlClass|htmlId|htmlStyle|htmlData)\b/.test(value)
        if (!blocked) rehypeKatex({ trust: false, maxExpand: 1000, maxSize: 10, output: 'htmlAndMathml', macros: {} })(local, file)
        if (blocked || file.messages.length > before) {
          parent.children[i] = { type: 'element', tagName: 'span', properties: { className: ['katex-error'] }, children: [{ type: 'text', value }] }
        } else {
          parent.children.splice(i, 1, ...local.children as Element[])
          i += local.children.length - 1
        }
      }
    }
    process(tree)
  }
}

function safeUrl(url: string): string {
  if (/[\\\u0000-\u0020\u007f]/.test(url)) return ''
  if (url.startsWith('#')) return url
  if (url.startsWith('/') && !url.startsWith('//')) {
    try { if (new URL(url, 'https://wcecoli.invalid').origin === 'https://wcecoli.invalid') return url } catch { /* invalid URL */ }
    return ''
  }
  try { const parsed = new URL(url); return ['https:', 'http:'].includes(parsed.protocol) ? url : '' } catch { return '' }
}

function textOf(node: RootContent): string {
  if (node.type === 'text') return node.value
  return 'children' in node ? node.children.map(textOf).join('') : ''
}

/** Read code from received Markdown rather than parser-added newlines or temporary repairs. */
function receivedCode(node: Element | undefined, source: string): string {
  if (!node) return ''
  const start = node.position?.start.offset
  const end = node.position?.end.offset
  const raw = source.slice(start ?? 0, Math.min(end ?? source.length, source.length))
  const opener = raw.match(/^(`{3,}|~{3,})[^\r\n]*(?:\r\n|\r|\n|$)/)
  if (opener) {
    const marker = opener[1][0]
    const body = raw.slice(opener[0].length)
    const closing = new RegExp(`^[ \\t>]*${marker}{${opener[1].length},}[ \\t]*$`, 'm')
    const match = closing.exec(body)
    const received = match ? body.slice(0, match.index) : body
    const parsed = textOf(node)
    // CommonMark handles indentation and blockquote prefixes. Its HTML conversion adds
    // one newline to code: keep it only when a newline was actually received.
    const ending = received.match(/(\r\n|\r|\n)$/)?.[1] ?? ''
    return parsed.replace(/\r?\n$/, ending)
  }
  // Indented code has already been de-indented by CommonMark.
  const parsed = textOf(node)
  const ending = raw.match(/(\r\n|\r|\n)$/)?.[1] ?? source.slice(end ?? source.length).match(/^(\r\n|\r|\n)/)?.[1] ?? ''
  return parsed.replace(/\r?\n$/, ending)
}

function CodeBlock({ text, language }: { text: string; language?: string }) {
  const [label, setLabel] = useState('Copy code')
  return <div className="assistant-code-block"><div className="assistant-code-toolbar">{language && <span>{language}</span>}<button className="assistant-copy" aria-label={label} onClick={async () => {
    try { await navigator.clipboard.writeText(text); setLabel('Copied code') } catch { setLabel('Copy unavailable') }
  }}>{label}</button></div><pre><code>{text}</code></pre></div>
}

function CopyOriginal({ text }: { text: string }) {
  const [label, setLabel] = useState('Copy original response')
  return <button className="assistant-copy" onClick={async () => {
    try { await navigator.clipboard.writeText(text); setLabel('Copied response') } catch { setLabel('Copy unavailable') }
  }}>{label}</button>
}

class FormattingBoundary extends Component<{ text: string; children: ReactNode }, { failed: boolean; attempt: number }> {
  state = { failed: false, attempt: 0 }
  static getDerivedStateFromError() { return { failed: true } }
  render() {
    return this.state.failed ? <div className="assistant-formatting-fallback"><p role="alert">Formatting unavailable. The original response is shown.</p><pre className="assistant-source">{this.props.text}</pre><CopyOriginal text={this.props.text} /><button className="assistant-copy" onClick={() => this.setState(state => ({ failed: false, attempt: state.attempt + 1 }))}>Retry formatting</button></div>
      : <div key={this.state.attempt}>{this.props.children}</div>
  }
}

function FormattedMarkdown({ text, mode, messageKey }: Required<MessageMarkdownProps>) {
  const prefix = useMemo(() => `assistant-${Array.from(messageKey).map(char => char.codePointAt(0)!.toString(16)).join('-')}-`, [messageKey])
  const display = useMemo(() => mode === 'complete' ? text : remend(text, incompleteOptions), [text, mode])
  const rehypePlugins = useMemo<NonNullable<Options['rehypePlugins']>>(() => [
    [presentationTree, { prefix }], [rehypeSanitize, schema],
    scientificMath,
  ], [prefix])
  const components: Components = useMemo(() => ({
    a: ({ href, children, node, ...props }) => {
      const url = safeUrl(href ?? '')
      if (!url) return <span>{children}</span>
      if (url.startsWith('#') && !url.startsWith('#' + prefix)) return <span>{children}</span>
      if (url.startsWith('#')) return <a {...props} href={url} onClick={event => {
        event.preventDefault()
        const region = event.currentTarget.closest('.assistant-messages')
        let id: string
        try { id = decodeURIComponent(url.slice(1)) } catch { return }
        const target = Array.from(region?.querySelectorAll<HTMLElement>('[id]') ?? []).find(element => element.id === id)
        if (target && region) {
          region.scrollTop += target.getBoundingClientRect().top - region.getBoundingClientRect().top - 12
          target.tabIndex = -1; target.focus({ preventScroll: true })
        }
      }}>{children}</a>
      return url.startsWith('/') ? <Link to={url}>{children}</Link> : <a href={url} target="_blank" rel="noopener noreferrer">{children}</a>
    },
    pre: ({ node }) => {
      const code = node?.children.find(child => child.type === 'element' && child.tagName === 'code') as Element | undefined
      const language = (code?.properties.className as string[] | undefined)?.find(value => value.startsWith('language-'))?.slice(9)
      return <CodeBlock text={receivedCode(node, text)} language={language} />
    },
    table: ({ node, children, ...props }) => <div className="assistant-table-scroll" tabIndex={0} aria-label="Response table"><table {...props}>{children}</table></div>,
    span: ({ node, className, children, ...props }) => className?.split(' ').includes('katex-error')
      ? <span className="assistant-equation-error"><code>{children}</code><span> Equation could not be formatted.</span></span>
      : <span className={className} {...props}>{children}</span>,
  }), [text, prefix])
  return <Markdown remarkPlugins={remarkPlugins} rehypePlugins={rehypePlugins} remarkRehypeOptions={{ clobberPrefix: '', footnoteLabel: 'Notes' }} components={components} urlTransform={safeUrl}>{display}</Markdown>
}

export const MessageMarkdown = memo(function MessageMarkdown({ text, mode = 'complete', messageKey }: MessageMarkdownProps) {
  const [source, setSource] = useState(false)
  return <div className="assistant-markdown" data-markdown-mode={mode}>
    {source ? <pre className="assistant-source">{text}</pre> : <FormattingBoundary key={messageKey} text={text}><FormattedMarkdown text={text} mode={mode} messageKey={messageKey} /></FormattingBoundary>}
    <button className="assistant-copy assistant-source-toggle" aria-pressed={source} onClick={() => setSource(value => !value)}>{source ? 'Formatted answer' : 'View source'}</button>
  </div>
})
