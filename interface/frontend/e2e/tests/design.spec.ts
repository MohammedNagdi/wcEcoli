test('condition changes ignore stale responses and never relabel previous-condition measurements', async ({ page }) => {
  let release: () => void = () => {}
  const pending = new Promise<void>(resolve => { release = resolve })
  await mockDesignApi(page, { overviewHandler: async route => {
    if (new URL(route.request().url()).searchParams.get('condition') === 'basal') { await pending; try { await route.fulfill({ json: overview() }) } catch {} }
    else await route.fulfill({ json: overview([gene('acetateGene', { mean_growth_rate: 0.000123 })], 'acetate') })
  } })
  await page.goto('/design')
  await expect(page.getByRole('heading', { name: 'Genome Design' })).toBeVisible()
  await page.getByLabel('Condition', { exact: true }).selectOption('acetate')
  await expect(tableRows(page)).toHaveCount(1)
  await expect(tableRows(page)).toContainText('acetateGene')
  release()
  await expect(page.getByLabel('Condition', { exact: true })).toHaveValue('acetate')
  await expect(tableRows(page)).toContainText('0.000123')
  await expect(page.getByRole('button', { name: 'Inspect dnaA', exact: true })).toHaveCount(0)
})

test('request failures have independent retries and successful empty evidence is explained', async ({ page }) => {
  let overviewRequests = 0, detailRequests = 0
  await mockDesignApi(page, {
    overviewHandler: async route => { overviewRequests++; await route.fulfill(overviewRequests === 1 ? { status: 503, json: { detail: 'Unavailable' } } : { json: overview([gene('dnaA', { phenotype: 'unknown', usable_result_count: 0 })]) }) },
    detailHandler: async route => { detailRequests++; await route.fulfill(detailRequests === 1 ? { status: 503, json: { detail: 'Unavailable' } } : { json: detail() }) },
  })
  await page.goto('/design')
  await expect(page.getByRole('heading', { name: 'Genome Design' })).toBeVisible()
  await expect(page.getByText('Could not load knockout evidence for basal.')).toBeVisible()
  await expect(page.getByText('No usable mechanistic knockout results for basal.')).toHaveCount(0)
  await page.getByRole('button', { name: 'Retry evidence', exact: true }).click()
  await expect(page.getByText('No usable mechanistic knockout results for basal.')).toBeVisible()
  await page.getByRole('button', { name: 'Inspect dnaA', exact: true }).click()
  await page.getByRole('button', { name: 'Retry gene evidence' }).click()
  await expect(page.getByText('Chromosomal replication initiator', { exact: true })).toBeVisible()
  expect(overviewRequests).toBe(2)
  expect(detailRequests).toBe(2)
})

