test('a failed same-condition refresh retains the last evidence and condition retry is independent', async ({ page }) => {
  let overviewRequests = 0, conditionRequests = 0
  await mockDesignApi(page, { overviewHandler: async route => { overviewRequests++; await route.fulfill(overviewRequests === 2 ? { status: 503, json: { detail: 'Offline' } } : { json: overview() }) } })
  await page.route('**/api/conditions', async route => { conditionRequests++; await route.fulfill(conditionRequests === 1 ? { status: 503, json: { detail: 'Offline' } } : { json: [{ name: 'basal' }, { name: 'acetate' }] }) })
  await page.goto('/design')
  await expect(tableRows(page)).toHaveCount(4)
  await page.getByRole('button', { name: 'Retry conditions' }).click()
  await expect(page.getByLabel('Condition', { exact: true }).locator('option')).toHaveCount(2)
  expect(overviewRequests).toBe(1)
  await page.getByRole('button', { name: 'Refresh evidence' }).click()
  await expect(page.getByText('Showing the last loaded evidence for this condition.')).toBeVisible()
  await expect(tableRows(page)).toHaveCount(4)
  await page.getByRole('button', { name: 'Retry evidence', exact: true }).click()
  await expect(page.getByText('Showing the last loaded evidence for this condition.')).toHaveCount(0)
  expect(conditionRequests).toBe(2)
})

test('late gene evidence cannot overwrite a newer inspector selection', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  let release: () => void = () => {}
  const pending = new Promise<void>(resolve => { release = resolve })
  await mockDesignApi(page, { detailHandler: async route => {
    const symbol = new URL(route.request().url()).pathname.split('/').pop()!
    if (symbol === 'dnaA') { await pending; try { await route.fulfill({ json: detail('dnaA') }) } catch {} }
    else await route.fulfill({ json: detail(symbol) })
  } })
  await page.goto('/design')
  await page.getByRole('button', { name: 'Inspect dnaA', exact: true }).click()
  await page.getByRole('button', { name: 'Inspect crp', exact: true }).click()
  await expect(page.locator('.design-inspector').getByRole('heading', { name: 'crp', exact: true })).toBeVisible()
  release()
  await expect(page.locator('.design-inspector')).toContainText('Chromosomal replication initiator')
  await expect(page.locator('.design-inspector').getByRole('heading', { name: 'dnaA', exact: true })).toHaveCount(0)
})
