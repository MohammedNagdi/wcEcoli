import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mockAssistantApi } from '../mocks/assistantApi'

const genes = ['dnaA', 'crp', 'passenger'].map((symbol, i) => ({ id: i+1, symbol, name: symbol, ecoli_id: `EG${i}`, ko_index: i === 2 ? -1 : 42+i, category: 'replication', is_mechanistic: true }))
async function setup(page: Page) {
  await page.route(/^https?:\/\/[^/]+\/api\//, r => r.fulfill({ json: [] }))
  await mockAssistantApi(page)
  await page.route('**/api/variants', r => r.fulfill({ json: ['wildtype','gene_knockout','multi_gene_knockout','timelines','tf_activity','param_sensitivity'].map(name => ({name, description: name})) }))
  await page.route('**/api/experiments/variants/*', r => r.fulfill({ json: {name: r.request().url().split('/').pop(), docstring:'Scientific notes', parameter_hints:{index_range:[0,10], timeline_behavior:'composer', tf_names:['CRP']} } }))
  await page.route('**/api/genes?*', r => r.fulfill({json:{genes,total:3,page:1,page_size:5000}}))
  await page.route('**/api/conditions', r=>r.fulfill({json:[{id:1,name:'basal',nutrients:'minimal',media_id:'minimal'}]}))
  await page.route('**/api/media-recipes',r=>r.fulfill({json:['minimal','minimal_acetate'].map((media_id,id)=>({id,media_id,base_media:media_id,added_media:'',ingredients:'[]'}))}))
  await page.route('**/api/timelines',r=>r.fulfill({json:[{name:'shift',definition:'0 minimal, 1800 minimal_acetate'}]}))
  await page.goto('/experiments/batch')
  await expect(page.getByLabel('Batch name',{exact:true})).toHaveValue('Batch preview')
}

test('keyboard selection, duplicates, row edits and unchanged batch payload',async({page})=>{
  await setup(page)
  expect(await page.locator('header .designer-status').count()).toBe(0)
  await expect(page.getByRole('button',{name:'Clear all',exact:true})).toHaveCount(0)
  await expect(page.getByText('Add at least one gene.',{exact:true})).toHaveCount(1)
  await page.getByLabel('Select dnaA',{exact:true}).focus(); await page.keyboard.press('Space')
  await page.getByLabel('Seeds',{exact:true}).fill('0, 7')
  await page.getByLabel('Include wildtype controls').check()
  const region=page.getByRole('region',{name:'Preview records',exact:true})
  await expect(region.locator('tbody tr')).toHaveCount(2)
  await region.getByRole('spinbutton').first().fill('9')
  await region.getByRole('button',{name:/Remove record/}).last().click()
  await page.getByRole('button',{name:'Restore 1',exact:true}).click()
  await page.getByRole('button',{name:'Reset edits',exact:true}).click()
  await expect(region.getByRole('spinbutton').first()).toHaveValue('0')
  let body:any
  await page.route('**/api/experiments/batch',r=>{body=r.request().postDataJSON();return r.fulfill({json:{batch_id:'test-batch',created:4}})})
  await page.getByRole('button',{name:'Create batch',exact:true}).click()
  await expect.poll(()=>body).toBeTruthy()
  expect(body).toMatchObject({name:'Batch preview',variant_type:'gene_knockout',include_wildtype:true})
  expect(body.records.map((r:any)=>r.seed)).toEqual([0,7])
  expect(body.records[0]).toMatchObject({variant_index:42,gene_symbol:'dnaA',generations:1})
  expect(JSON.parse(body.records[0].sim_params)).toEqual({seed:0,generations:1,length_sec:10800})
  await expect(page).toHaveURL(/batch=test-batch/)
})

