for(const width of [390,768,1440]) for(const theme of ['light','dark','system']) test(`batch layout ${width} ${theme}, reduced motion and effective 200% zoom`,async({page})=>{
  await page.setViewportSize({width,height:1000});await page.emulateMedia({colorScheme:theme==='light'?'light':'dark',reducedMotion:'reduce'})
  await page.addInitScript(t=>localStorage.setItem('wcecoli.theme',t),theme)
  await setup(page);await page.getByLabel('Select dnaA',{exact:true}).check()
  expect((await new AxeBuilder({page}).include('.batch-designer').analyze()).violations).toEqual([])
  for(const w of [width,Math.floor(width/2)]) {
    await page.setViewportSize({width:w,height:1000})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
    const cancel=page.locator('.designer-summary').getByRole('link',{name:'Cancel',exact:true})
    await cancel.scrollIntoViewIfNeeded();await expect(cancel).toBeInViewport()
    expect(await page.locator('main').evaluate(e=>getComputedStyle(e).overflowY)).toBe('auto')
    await page.locator('main').evaluate(e=>{e.scrollTop=0})
    await page.mouse.move(w-25,500);await page.mouse.wheel(0,600)
    await expect.poll(()=>page.locator('main').evaluate(e=>e.scrollTop)).toBeGreaterThan(0)
  }
  await page.locator('.designer-summary').getByRole('link',{name:'Cancel',exact:true}).click()
  await expect(page).toHaveURL(/\/experiments$/)
})

